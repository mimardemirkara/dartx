self.addEventListener('install', e => {
  // cache:'reload' — GitHub'ın 10 dakikalık tarayıcı önbelleğini atla, yeni sürümün dosyaları gerçekten yeni insin
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(FILES.map(u => new Request(u, { cache: 'reload' })))).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k !== VERSION).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Önce önbellek, yoksa ağ
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  // Bilgisayardaki önizleme (localhost): önbellek atlanır, her zaman güncel dosya gelir (Demir 09.11: yerelde güncelle, sonra yayınla)
  if (['localhost', '127.0.0.1'].includes(location.hostname)) return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then(hit => hit || fetch(e.request).then(res => {
      if (res.ok && new URL(e.request.url).origin === location.origin) {
        const copy = res.clone();
        caches.open(VERSION).then(c => c.put(e.request, copy));
      }
      return res;
    }).catch(() => caches.match('index.html')))
  );
});
